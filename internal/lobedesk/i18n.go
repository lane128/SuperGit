// chineseEnglishTerms lists the words the Chinese interface keeps in English
// on purpose. Everything else is translated: a Git action the reader knows by
// its Chinese name (提交、分支、合并、变基、获取、推送、暂存) stays Chinese, while
// product names and the few Git objects that have no settled Chinese name stay
// as Git spells them. The reasoning is docs/git-terms.md; the test
// TestChineseStringsOnlyKeepTheListedEnglishTerms fails on any other Latin
// word in a Chinese string, so a new term is a decision rather than a slip.
var chineseEnglishTerms = []string{
	// Products and platforms.
	"Git", "SuperGit", "Sublime", "Text", "LFS", "Flow", "Lobe", "MyGo", "Catppuccin", "Frappe", "Macchiato", "Finder", "UI",
	// User-approved Diff palette setting and its CLI-inspired scheme name.
	"Diff", "Delta",
	// Git objects and flags that the interface names in Git's own words.
	"Stash", "HEAD", "detached", "SHA", "Ours", "Theirs", "hooks", "force-with-lease", ".gitmodules",
}

func (a *app) t(key string) string {
	key = externalPathMessageKey(runtime.GOOS, key)
	if table, ok := messages[a.locale]; ok {
		if value, ok := table[key]; ok {
			return value
		}
	}
	return key
}

func (a *app) tf(key string, args ...any) string {
	return fmt.Sprintf(a.t(key), args...)
}

