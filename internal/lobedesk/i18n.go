// branchesLabel counts what the branches page lists: local branches, remote
// branches and tags. Counting only the local ones made a page dominated by a
// fetched remote's refs read "1 local branch".
func (a *app) branchesLabel(local, remote, tags int) string {
	return a.branchesSubtitle(local, remote, tags, false, false, false)
}

// branchesSubtitle is branchesLabel with a way to say that a group's read
// failed. A count of zero would claim the repository has no refs of that kind,
// which the page does not know; "unavailable" is what it knows.
func (a *app) branchesSubtitle(local, remote, tags int, localFailed, remoteFailed, tagsFailed bool) string {
	if a.locale == localeEnglish {
		part := func(failed bool, n int, one, many, unavailable string) string {
			if failed {
				return unavailable
			}
			return fmt.Sprintf("%d %s", n, plural(n, one, many))
		}
		return strings.Join([]string{
			part(localFailed, local, "local branch", "local branches", "local branches unavailable"),
			part(remoteFailed, remote, "remote branch", "remote branches", "remote branches unavailable"),
			part(tagsFailed, tags, "tag", "tags", "tags unavailable"),
		}, " · ")
	}
	part := func(failed bool, n int, name string) string {
		if failed {
			return name + "读取失败"
		}
		return fmt.Sprintf("%d 个%s", n, name)
	}
	return strings.Join([]string{
		part(localFailed, local, "本地分支"),
		part(remoteFailed, remote, "远端分支"),
		part(tagsFailed, tags, "标签"),
	}, " · ")
}

// hunksLabel counts the diff hunks a pane shows. The singular case exists
// because English reads "1 hunks" as a mistake; the Chinese string has no
// plural form.
// workspacesLabel counts worktrees and submodules for the worktrees page's
// subtitle, with the singular where English needs it.
func (a *app) workspacesLabel(worktrees, submodules int) string {
	return a.workspacesSubtitle(worktrees, submodules, false, false)
}

// workspacesSubtitle is workspacesLabel with a way to say that one group's
// read failed. The two reads are separate, so a worktree failure must not
// claim the submodule list is empty.
