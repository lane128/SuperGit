// fetchIntervalLabel names an interval in the reader's language; 0 is the
// "only on open" choice rather than a duration of zero.
func (a *app) fetchIntervalLabel(minutes int) string {
	if minutes <= 0 {
		return a.t("autoFetchOff")
	}
	if a.locale == localeEnglish {
		if minutes == 60 {
			return "1 hour"
		}
		return fmt.Sprintf("%d min", minutes)
	}
	if minutes == 60 {
		return "1 小时"
	}
	return fmt.Sprintf("%d 分钟", minutes)
}

func (a *app) diffSummary(additions, deletions, hunks int) string {
	if a.locale == localeEnglish {
		return fmt.Sprintf("%d %s · %d %s · %d %s",
			additions, plural(additions, "addition", "additions"),
			deletions, plural(deletions, "deletion", "deletions"),
			hunks, plural(hunks, "hunk", "hunks"))
	}
	return fmt.Sprintf("%d 新增 · %d 删除 · %d 个片段", additions, deletions, hunks)
}

func plural(n int, one, many string) string {
	if n == 1 {
		return one
	}
	return many
}
